import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const root = path.resolve(import.meta.dirname, '..');
const hash = value => crypto.createHash('sha256').update(value).digest('hex').slice(0, 12);
const moduleText = fs.readFileSync(path.join(root, 'reading-inline.mjs'), 'utf8');
const cssText = fs.readFileSync(path.join(root, 'reading-inline.css'), 'utf8');
const moduleName = `reading-inline.${hash(moduleText)}.mjs`;
const cssName = `reading-inline.${hash(cssText)}.css`;
fs.writeFileSync(path.join(root, moduleName), moduleText);
fs.writeFileSync(path.join(root, cssName), cssText);
const manifest = [];
const manifestPath = path.join(root, 'tests/reading-inline-manifest.json');
const baseline = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath)) : [];
for (const directory of fs.readdirSync(root).filter(name => name.startsWith('ri3-'))) {
  const htmlPath = path.join(root, directory, 'index.html');
  let html = fs.readFileSync(htmlPath, 'utf8');
  const current = html.match(/src="\.\/(assets\/[^" ]+\.js)"/)[1];
  const previous = baseline.find(entry => entry.directory === directory)?.previous ?? current;
  let source = fs.readFileSync(path.join(root, directory, previous), 'utf8');
  if (source.includes('__riInlineGroup')) throw new Error('Use an unpatched baseline: ' + directory);
  const start = source.indexOf('n.map(t=>(0,O.jsxs)(`div`,{className:`exercise-group`');
  const endMarker = '},`${e}-${t.label||`main`}`))';
  const end = source.indexOf(endMarker, start) + endMarker.length;
  if (start < 0 || end < start) throw new Error('Unknown group renderer: ' + directory);
  const original = source.slice(start, end);
  const fallback = original.slice('n.map(t=>'.length, -1);
  const replacement = 'n.map(t=>__riPlan(t.label,t.items)?(0,O.jsx)(__riInlineGroup,{label:t.label,items:t.items,answers:a,words:s,setAnswer:(id,value)=>o(n=>({...n,[id]:value})),setWord:(id,value)=>c(n=>({...n,[id]:value})),submitted:d},`${e}-${t.label||`main`}`):' + fallback + ')';
  source = source.slice(0, start) + replacement + source.slice(end);
  const mount = '(0,ue.createRoot)(document.getElementById(`root`))';
  if (source.split(mount).length !== 2) throw new Error('Unknown mount: ' + directory);
  source = source.replace(mount, 'const __riInlineGroup=__riCreate(O,$e,nt,rt);' + mount);
  source = `import {planInline as __riPlan,createInlineGroup as __riCreate} from '../../${moduleName}';\n` + source;
  const next = `assets/index-inline-${hash(source)}.js`;
  fs.writeFileSync(path.join(root, directory, next), source);
  html = html.replace(current, next).replace(/\s*<link rel="stylesheet" href="\.\.\/reading-inline\.[a-f0-9]+\.css">/, '').replace('</head>', `  <link rel="stylesheet" href="../${cssName}">\n  </head>`);
  fs.writeFileSync(htmlPath, html);
  manifest.push({ directory, previous, next });
}
fs.writeFileSync(path.join(root, 'tests/reading-inline-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`Updated ${manifest.length} lesson entry points.`);
